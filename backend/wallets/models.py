class MonetizationGoal(TimeStampedModel):
    """
    Creator earnings goal.
    """

    user = models.ForeignKey(
        settings.AUTH_USER_MODEL,
        on_delete=models.CASCADE,
        related_name="monetization_goals",
    )

    title = models.CharField(
        max_length=150,
    )

    target_amount = models.DecimalField(
        max_digits=18,
        decimal_places=2,
        validators=[
            MinValueValidator(
                Decimal("0.01")
            )
        ],
    )

    current_amount = models.DecimalField(
        max_digits=18,
        decimal_places=2,
        default=ZERO,
        validators=[MinValueValidator(ZERO)],
    )

    currency = models.CharField(
        max_length=3,
        default="NGN",
    )

    is_active = models.BooleanField(
        default=True,
    )

    created_at = models.DateTimeField(
        auto_now_add=True,
    )

    completed_at = models.DateTimeField(
        blank=True,
        null=True,
    )

    class Meta:
        ordering = ["-created_at"]

        indexes = [
            models.Index(
                fields=[
                    "user",
                    "is_active",
                ],
            ),
        ]

    def __str__(self):
        return (
            f"{self.user} - "
            f"{self.title}"
        )

    @property
    def progress_percentage(self):
        if self.target_amount <= ZERO:
            return Decimal("0")

        percentage = (
            self.current_amount /
            self.target_amount
        ) * Decimal("100")

        return min(
            percentage,
            Decimal("100"),
        )